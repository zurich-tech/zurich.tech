import { For } from "solid-js";

/** One semantic ASCII color and behavior. */
type AsciiTone = "ink" | "light" | "soft" | "star" | "water";

/** One contiguous ASCII run. */
type AsciiRun = {
    /** The animation offset in seconds. */
    phase?: number;
    /** The visible characters. */
    text: string;
    /** The run color and behavior. */
    tone?: AsciiTone;
};

/** ASCII art properties. */
type AsciiArtProps = {
    /** The presentation class. */
    class: string;
    /** The categorized rows. */
    rows: readonly (readonly AsciiRun[])[];
};

/** Semantic tones encoded by visible postcard glyphs. */
const toneByGlyph: Readonly<Record<string, AsciiTone>> = {
    "-": "ink",
    "/": "ink",
    "*": "light",
    "+": "ink",
    ".": "star",
    "\\": "ink",
    "|": "ink",
    _: "ink",
    "~": "water",
};

