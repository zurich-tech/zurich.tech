/** Render categorized ASCII rows. */
function AsciiArt(props: AsciiArtProps) {
    return (
        <pre aria-hidden="true" class={props.class}>
            <For each={props.rows}>
                {(runs) => (
                    <span class="zurich-postcard__line">
                        {/* runs */}
                        <For each={runs}>
                            {(run) => (
                                <span
                                    class={
                                        run.tone === undefined
                                            ? undefined
                                            : `zurich-postcard__run--${run.tone}`
                                    }
                                    style={
                                        run.phase === undefined
                                            ? undefined
                                            : `--ascii-phase: -${run.phase}s`
                                    }
                                >
                                    {run.text}
                                </span>
                            )}
                        </For>
                    </span>
                )}
            </For>
        </pre>
    );
}

/** Decode encoded source rows into semantic ASCII runs. */
function createAsciiRows(source: readonly string[], width: number): readonly AsciiRun[][] {
    // validate the rectangular source
    for (const row of source) {
        if (row.length !== width) {
            throw new Error(`Invalid ASCII row width: ${row.length}`);
        }
    }

    // combine neighboring characters with the same tone
    const rows: AsciiRun[][] = [];
    for (let y = 0; y < source.length; y += 1) {
        const runs: AsciiRun[] = [];
        for (let x = 0; x < width; x += 1) {
            const glyph = source[y][x];
            const tone = glyph === "?" ? undefined : toneByGlyph[glyph];
            if (glyph !== "?" && tone === undefined) {
                throw new Error(`Unsupported ASCII glyph: ${glyph}`);
            }

            // append to the current run when its tone matches
            const text = glyph === "?" ? " " : glyph === "~" ? "_" : glyph;
            const previous = runs.at(-1);
            if (previous !== undefined && previous.tone === tone) {
                previous.text += text;
                continue;
            }

            // phase each new animated run deterministically
            const isAnimated = tone === "light" || tone === "star";
            const phase = isAnimated ? ((x * 17 + y * 31) % 48) / 10 : undefined;
            runs.push({ phase, text, tone });
        }
        rows.push(runs);
    }

    return rows;
}
