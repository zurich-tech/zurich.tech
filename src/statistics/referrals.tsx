import { createResource, createSignal, For, Show } from "solid-js";
import { RefreshCw } from "lucide-solid";
import { api } from "../../convex/_generated/api";
import { memberClient } from "../auth/convex";
import { Card } from "../components/card";
import { FormMessage } from "../components/form";
import { Loading } from "../components/loading";
import { useWorkspaceCommand } from "../app/workspace";

/** Create direct campaign links and inspect aggregate arrivals. */
export function Referrals() {
    // load reports only within the administrator workspace
    const [links, { refetch }] = createResource(async () =>
        (await memberClient()).query(api.statistics.referrals.list, {}),
    );
    const [created, setCreated] = createSignal("");
    const [isCreating, setIsCreating] = createSignal(false);
    const command = useWorkspaceCommand(refetch);

    /** Register the selected dimensions and return a shareable destination URL. */
    async function create(event: SubmitEvent) {
        // read the four explicit campaign fields
        event.preventDefault();
        const form = new FormData(event.currentTarget as HTMLFormElement);
        const fields = {
            path: String(form.get("path")).trim(),
            source: String(form.get("source")).trim(),
            medium: "social",
            campaign: String(form.get("campaign")).trim(),
        };

        // retain the direct URL without visiting or counting it
        await command.perform(async () => {
            setCreated(
                await (await memberClient()).mutation(api.statistics.referrals.create, fields),
            );
        }, "Link ready.");
    }

    return (
        <>
            {/* social links are copied into posts, email links are generated by the sender */}
            <Show when={isCreating()}>
                <Card
                    title="Social link"
                    toolbar={
                        <button class="action-link" onClick={() => setIsCreating(false)}>
                            Close
                        </button>
                    }
                >
                    <form class="editor" onSubmit={create}>
                        <div class="form-columns">
                            <label>
                                Page
                                <input
                                    name="path"
                                    required
                                    maxLength={200}
                                    placeholder="/news/introducing-zurich-tech"
                                />
                            </label>
                            <label>
                                Campaign
                                <input
                                    name="campaign"
                                    required
                                    maxLength={64}
                                    pattern="[a-z0-9][a-z0-9_\-]*"
                                    placeholder="launch-2026"
                                />
                            </label>
                            <label>
                                Platform
                                <select name="source">
                                    <option value="linkedin">LinkedIn</option>
                                    <option value="x">X</option>
                                    <option value="discord">Discord</option>
                                </select>
                            </label>
                        </div>
                        {/* create without opening the destination */}
                        <div class="row-actions">
                            <button class="button" disabled={command.isPending()} type="submit">
                                Create link
                            </button>
                        </div>
                        <FormMessage error={command.error()} success={command.success()} />
                        <Show when={created()}>
                            <label>
                                URL
                                <input
                                    readOnly
                                    value={created()}
                                    onFocus={(event) => event.currentTarget.select()}
                                />
                            </label>
                        </Show>
                    </form>
                </Card>
            </Show>

            {/* aggregate report */}
            <Card
                title="Campaign arrivals"
                meta="Last 30 days · Zurich time"
                toolbar={
                    <>
                        <button class="action-link" onClick={() => setIsCreating(true)}>
                            New social link
                        </button>
                        <button
                            class="button"
                            aria-label="Refresh arrivals"
                            title="Refresh arrivals"
                            onClick={() => void refetch()}
                        >
                            <RefreshCw size={16} aria-hidden="true" />
                        </button>
                    </>
                }
            >
                <Show
                    when={links()}
                    fallback={
                        <Show when={links.error} fallback={<Loading />}>
                            <p class="form-error">Could not load campaign arrivals.</p>
                        </Show>
                    }
                >
                    <Show when={links()?.length} fallback={<p>No campaign links.</p>}>
                        <div class="table-scroll">
                            <table class="admin-table">
                                <thead>
                                    <tr>
                                        <th>Campaign</th>
                                        <th>Arrivals</th>
                                        <th>Source</th>
                                        <th>Medium</th>
                                        <th>Page</th>
                                        <th>Daily counts</th>
                                    </tr>
                                </thead>
                                <tbody>
                                    <For each={links()}>
                                        {(link) => (
                                            <tr>
                                                <td>{link.campaign}</td>
                                                <td>
                                                    {link.days.reduce(
                                                        (total, day) => total + day.count,
                                                        0,
                                                    )}
                                                </td>
                                                <td>{link.source}</td>
                                                <td>{link.medium}</td>
                                                <td>
                                                    <a class="text-link" href={link.url}>
                                                        {link.path}
                                                    </a>
                                                </td>
                                                <td>
                                                    <details>
                                                        <summary>By day</summary>
                                                        <For each={link.days}>
                                                            {(day) => (
                                                                <div>
                                                                    {day.date}: {day.count}
                                                                </div>
                                                            )}
                                                        </For>
                                                    </details>
                                                </td>
                                            </tr>
                                        )}
                                    </For>
                                </tbody>
                            </table>
                        </div>
                    </Show>
                </Show>
            </Card>
        </>
    );
}
